// Main testbench: the whole CPU + PIC + mtimer system under one self-checking
// run.
//
// Setup (a small SoC):
// - cpu_top, imem model @ 0x0000 on the ibus
// - dbus through two address decoders: the 0x3000_0000 window splits into the
//   real pic (0x3000_0000) and the real mtimer (0x3001_0000); everything else
//   goes to the dmem model @ 0x2000 (DECERR out of its range)
// - passive AXI protocol monitors on ibus, dbus, the PIC and mtimer ports
// - the TB plays the peripherals on irq_src[6:0] the way the DMA/DP-SRAM would
//   (raise on event, hold until "cleared"); channel 7 is the real mtimer irq
//
// program_axi.s exercises every ISA group, every sync trap cause, the CSR rules
// and the PIC registers; results land in registers and a dmem scoreboard,
// checked after the end marker (x23 = 0x123). Invariants are sampled every cycle
// (ack shape, PIC consistency), and monitor error counters must end at 0.
//
// Interrupt choreography (why each source moves the way it does):
// - src5 rises after reset and stays up: enabled in the PIC but never in mie, so
//   it must never be taken (no ack[5]), which proves the two masks are independent
// - src2 + src3 rise together once MIE is set: ch2 served first (priority), ch3
//   right after ch2's MRET; src3 stays high through its handler, so the
//   in-service mask keeps it out of cpu_irq (suppression) and it's taken once
// - src2 rises again while a data-bus read is in flight: the ack may only come
//   after the R beat: held through the stall, taken at the boundary, load intact

// label addresses, generated by asm.py next to program_axi.hex, so a code
// change that shifts a label updates the checks automatically (see +incdir)
`timescale 1ns/1ps

